"""Лёгкая эвристика типа вопроса -> коллекции для дефолта search() (контракт
v0.3, ревью 02, п.3). НЕ полноценный NLU — тот остаётся ответственностью
вызывающего (см. v0.2.4: «извлечение Filters из реплики — ответственность
/chat»). Это только грубая маршрутизация по ключевым словам, чтобы дефолтный
search() без явных collections не мешал в одну кучу карточки вина и статьи
(см. отчёт A: «вытеснение карточек вина статьями» — hit@8 pick/pairing
разваливался именно от этого при дефолте contracts/rag-interface.md v0.2).

Приоритет проверок: travel -> fact -> pairing/pick -> дефолт контракта
(wines+knowledge), первое совпадение побеждает.

Pairing-подобные запросы (приёмка F, лог демо-сцены 2 — «Что взять к сырам?»
приносил 8 цитат ИЗ СТАТЕЙ вместо карточек вин) размечаются ОТДЕЛЬНО от
travel/fact: `classify()` возвращает `"pairing"`, а не готовый кортеж
коллекций — `Retriever.search()` реализует для него приоритет «wines
приоритетно, knowledge — добивкой» (см. `PAIRING_PRIMARY`/`PAIRING_FALLBACK`
и докстринг `Retriever.search`), а не жёсткое исключение knowledge: если
вин в фильтрованном пуле не хватило на top_k, остаток добирается статьями,
а не наоборот.

reports/backend-chat-retrieval.md (22.09, разбор EMPTY_RETRIEVAL на фразе
задания «Посоветуй красное к стейку до 2000 рублей»): у `classify()` было
ДВА слепых пятна, из-за которых типовые вопросы жюри («Белое до 1500»,
«Посоветуй что-нибудь к рыбе», «Розовое к лёгкому ужину», «Что-нибудь из
Крыма» — без лексемы «вин[оаеуы]» и без глагола «подать/взять/выбрать/
заказать») уходили в default-ветку (`collections=("wines","knowledge")`,
`apply_refusal=True`) вместо pairing (`wines`-приоритет, refusal НЕ
проверяется на первом проходе): (1) сигнал был ЧИСТО текстовый, хотя
`Retriever.search()` уже получает `filters` — непустой Filters (цвет/сахар/
регион/сорт), извлечённый детерминированно из той же таксономии вина
(apps/api/app/chat/filters.py), теперь тоже считается "вопрос про вино"
(`classify(query, filters)`, `filters_active()`, rag/types.py) — не ловит
посторонние вопросы («Посоветуй фильм ужасов» не даёт ни одного поля
Filters); (2) короткий гастро-фрагмент «к/под …» матчился только ЯКОРЕМ в
начале строки (старый `_SHORT_PAIRING_FRAGMENT_RE`) — «Посоветуй что-нибудь
к рыбе» (27 симв., фрагмент не в начале) уходил в default. Регэксп ниже
теперь ищет тот же короткий фрагмент ГДЕ УГОДНО в пределах лимита длины (защита от ложных
срабатываний внутри длинных предложений — длина, не позиция), проверено на
всех 78 вопросах packages/rag/eval/goldset.jsonl (11 refusal — ни один не
матчится ни по длине, ни по токену) и на всех pick/pairing — 0 регрессий,
см. отчёт.

Ни то, ни другое НЕ трогает эвристику для калибровки/eval (rag/calibrate.py,
rag/eval.py) — обе зовут `Retriever.search()`/`infer_collections()` БЕЗ
`filters` (текст голд-сета не несёт Filters), так что `hit@8` на голд-сете
не мог измениться от пункта (1) по построению; пункт (2) — чисто текстовый и
проверен отдельно (см. выше).
"""
from __future__ import annotations

import re

from rag.types import Filters, filters_active

# 22.09 (reports/backend-rag-rebuild.md): кнопка "Спросить сомелье об этом
# вине" (ScanScreen.tsx::handleAskSomelierAboutResult, WineCardScreen.tsx::
# handleAskSomelier — точные номера строк на 22.09 см. отчёт, дрейфуют с
# параллельной работой frontend) шлёт ровно t("chat.prefillAskAboutWine") =
# "Расскажи про {name} от {winery}" (apps/web/src/i18n/ru.ts, ключ
# prefillAskAboutWine). Эта фраза — ЧАСТНЫЙ случай "расскажи про
# <нечто>", который _FACT_RE ниже ловил ДО этой правки (стем "расскаж" +
# "про" — паттерн `расскаж.{0,3} про`, задуманный для "расскажи про танины"),
# отправляя её в collections=("knowledge",) — коллекция "wines" не участвует
# в поиске ВООБЩЕ, и slug вина не может попасть в кандидатов ни при каких
# обстоятельствах, даже если он есть в индексе. Для винодельни, чьё имя само
# содержит "винодельня" (Винодельня Орлова, Винодельня Братьев Мельниковых —
# 2 из 21 винодельни на пропущенных 125 вин, reports/backend-rag-rebuild.md),
# _TRAVEL_RE перехватывал её ещё раньше, тем же результатом (wines не
# участвует). Проверено: это ПОЛНОСТЬЮ объясняет симптом тимлида "сомелье не
# знает" независимо от того, есть ли вино в индексе — затронуты ВСЕ вина
# каталога, не только 125 новых. Паттерн ниже — точная форма шаблона фронта
# ("расскажи про X от Y"): якорь ^ + оба слова "про"/"от" отдельными
# словами исключают ложные совпадения в середине длинных вопросов о чём-то
# постороннем (ни один из 78 вопросов packages/rag/eval/goldset.jsonl не
# матчится — единственный вопрос со словом "расскаж" в голдсете,
# "Расскажите про винодельню Абрау-Дюрсо.", не несёт " от " и по-прежнему
# уходит в travel, см. test_intent_routing.py). Классифицируем как "pairing"
# (не заводим новую ветку): семантически то же самое желание — приоритет
# wines, knowledge только добивкой, если карточек не хватило (см.
# Retriever._search_pairing) — ровно то, что нужно вопросу про конкретное вино.
_ASK_ABOUT_WINE_RE = re.compile(r"^расскаж.{0,3}\s+про\s+.+\s+от\s+.+", re.IGNORECASE)

_TRAVEL_RE = re.compile(
    r"винодельн|вино.?тур|винный тур|экскурси|куда (съездить|поехать)|"
    r"путешеств|посетить|дегустационн.?(зал|комнат)",
    re.IGNORECASE,
)
_FACT_RE = re.compile(
    r"^что такое|^почему|^откуда|^как называ|^зачем|что означает|в чём разниц|"
    r"чем отлича|из чего (сделан|образ)|расскаж.{0,3} про|как понять",
    re.IGNORECASE,
)
_PAIRING_RE = re.compile(
    r"вин[оаеуы]\b|"  # «вино/вина/вине/вину/вины» — сама лексема, не «винодельня» (та ловится travel-веткой раньше)
    r"что (подать|взять|выбрать|заказать)\b",  # гастропара без слова «вино»: «что взять к сырам»
    re.IGNORECASE,
)
# ПРИМЕЧАНИЕ: голые глаголы-рекомендации («посоветуй», «подбери», «найди» без
# упоминания вина/еды) сюда НЕ входят — были в первой версии правки и ловили
# «Посоветуй фильм ужасов» в pairing, из-за чего эта конкретная garbage-фраза
# обходила refusal (см. Retriever._search_pairing) и hit@8 голд-сета просел
# 0.8267->0.8133. Проверено: все 30 pick/pairing вопросов голд-сета и так
# содержат лексему «вин[оаеуы]» или «что подать/взять/выбрать/заказать» — эти
# глаголы не добавляли покрытия, только ложные срабатывания на не-винных фразах.
# Терпимый гастро-фрагмент без глагола — реплика-продолжение в чате
# («к устрицам», «под стейк») ИЛИ короткий гастро-хвост целой фразы
# («Посоветуй что-нибудь к рыбе» — см. модульный докстринг, 22.09): предлог
# «к»/«под» как отдельное слово, ГДЕ УГОДНО в пределах лимита длины, не
# обязательно в начале строки. Защита от ложных срабатываний — сам лимит
# длины (короткая фраза целиком про гастро-подбор), не позиция: длинное
# предложение вида «Расскажи подробнее, к чему может привести долгая
# выдержка в дубе» отсекается длиной (>30 симв.), а не тем, что «к» не
# первое слово — иначе поймали бы полкаталога фактов не туда. \b перед
# группой и \s+ сразу после неё требуют «к»/«под» ИМЕННО отдельным словом
# (не начало «как»/«код», не «попурри»), см. rag/eval/goldset.jsonl.
_SHORT_PAIRING_FRAGMENT_RE = re.compile(r"\b(к|под)\s+\S", re.IGNORECASE)
_SHORT_FRAGMENT_MAX_LEN = 30

DEFAULT_COLLECTIONS: tuple[str, ...] = ("wines", "knowledge")
PAIRING_PRIMARY: tuple[str, ...] = ("wines",)
PAIRING_FALLBACK: tuple[str, ...] = ("wines", "knowledge")


def _is_pairing_like(q: str) -> bool:
    if _PAIRING_RE.search(q):
        return True
    return len(q) <= _SHORT_FRAGMENT_MAX_LEN and bool(_SHORT_PAIRING_FRAGMENT_RE.search(q))


def classify(query: str, filters: Filters | None = None) -> str:
    """pairing | travel | fact | default — первое совпадение по приоритету.

    `filters` — опционально, уже извлечённые Filters (color/sugar/region/
    grapes/stillness, apps/api/app/chat/filters.py). Непустой Filters —
    дополнительный, точный сигнал "вопрос про вино" (reports/
    backend-chat-retrieval.md, 22.09, см. докстринг модуля): в отличие от
    расширения текстовых паттернов ниже, он НЕ рискует поймать посторонний
    вопрос («Посоветуй фильм ужасов» не извлекает ни одного поля). Дефолт
    None сохраняет старое чисто-текстовое поведение — используется
    rag.calibrate/rag.eval, которые вызывают search()/classify() без Filters
    вообще (см. докстринг модуля).

    `_ASK_ABOUT_WINE_RE` (см. её докстринг выше, 22.09) проверяется ПЕРВЫМ,
    раньше travel/fact — иначе "Расскажи про {вино} от {винодельня}" (кнопка
    "Спросить сомелье об этом вине") либо совпадает с фрагментом "расскаж
    ... про" в _FACT_RE, либо, если имя винодельни само содержит
    "винодельня", ещё раньше — с _TRAVEL_RE; и то, и другое исключает
    коллекцию wines из поиска целиком."""
    q = (query or "").strip()
    if not q:
        return "default"
    if _ASK_ABOUT_WINE_RE.search(q):
        return "pairing"
    if _TRAVEL_RE.search(q):
        return "travel"
    if _FACT_RE.search(q):
        return "fact"
    if _is_pairing_like(q) or filters_active(filters):
        return "pairing"
    return "default"


def infer_collections(query: str) -> tuple[str, ...]:
    """Готовый кортеж collections для однократного вызова search() — используется
    везде, КРОМЕ pairing (там нужен приоритет с добивкой, а не один кортеж,
    см. Retriever.search и docstring модуля)."""
    kind = classify(query)
    if kind == "travel":
        return ("wineries", "knowledge")
    if kind == "fact":
        return ("knowledge",)
    if kind == "pairing":
        return PAIRING_PRIMARY
    return DEFAULT_COLLECTIONS
