"""Тесты `cv/label_crop.py` (agents/H3-label-crop-ocr.md, задача 1) — `label_bbox()`,
перенесённый ДОСЛОВНО из `qa/real_photos_label_crops.py` (эквивалентность проверена
отдельно fuzz-сравнением с прототипом на 500 случайных наборах боксов, не входит в
этот файл — здесь только читаемые синтетические сценарии по категориям брифа:
кластеризация по вертикали, минимальный размер, рост вниз, фолбэк на None).

Синтетический кадр везде w=1000, h=2000 (портретная бутылка). Боксы — 4-точечные
полигоны `[[x0,y0],[x1,y0],[x1,y1],[x0,y1]]`, как отдаёт `rapidocr` (`RapidOCROutput.
boxes`) — `label_bbox()` использует только min/max по координатам, порядок точек
внутри бокса не важен (не тестируется отдельно — тривиальное свойство `np.asarray(...).
min()/.max()`).
"""
from __future__ import annotations

import pytest

from cv.label_crop import label_bbox

W, H = 1000.0, 2000.0


def box(x0: float, y0: float, x1: float, y1: float) -> list[list[float]]:
    return [[x0, y0], [x1, y0], [x1, y1], [x0, y1]]


# --------------------------------------------------------------------------------------
# Фолбэк на None — законный исход, не ошибка (докстринг модуля): вызывающий код
# (cv.ocr_rapid) трактует None как "пропустить третий проход", скрипт-исследование
# (qa/real_photos_label_crops.py::main) — как "взять весь кроп бутылки"; сам
# label_bbox() решения о фолбэке не принимает, только сигнализирует отсутствие кандидата.
# --------------------------------------------------------------------------------------


def test_returns_none_on_empty_boxes():
    assert label_bbox([], [], W, H) is None


def test_returns_none_when_all_boxes_below_score_threshold():
    # score=0.5 — граница ВКЛЮЧЕНА (>=, значит < отсекает) — 0.49 явно ниже
    assert label_bbox([box(400, 900, 600, 960)], [0.49], W, H) is None


def test_returns_none_when_all_boxes_outside_center_column():
    # cx=50 -> 0.05*w, вне [0.18w, 0.82w]=[180, 820] — боковая деталь (соседняя бутылка/рука)
    assert label_bbox([box(0, 900, 100, 960)], [0.9], W, H) is None


def test_returns_none_when_all_boxes_below_min_height():
    # высота 10 < 0.008*h=16 — микро-артефакт детектора, не строка текста
    assert label_bbox([box(450, 900, 550, 910)], [0.9], W, H) is None


def test_score_threshold_boundary_is_inclusive():
    """Ровно 0.5 — засчитывается (`s < 0.5` отсекает, не `s <= 0.5`), симметрично
    порогу распознавания в cv.ocr_rapid.RapidOcrReader (>=, не >)."""
    result = label_bbox([box(300, 1000, 700, 1060)], [0.5], W, H)
    assert result is not None


# --------------------------------------------------------------------------------------
# Одиночный бокс — без кластеризации, но поля + минимальный размер применяются
# --------------------------------------------------------------------------------------


def test_single_large_box_gets_margins_without_floor_expansion():
    """Бокс уже достаточно большой (после полей ширина/высота выше минимума) —
    результат — ровно бокс + поля, без срабатывания пола/симметричного роста."""
    result = label_bbox([box(200, 900, 800, 1600)], [0.9], W, H)
    assert result == pytest.approx((72.0, 755.0, 928.0, 1745.0))
    # сверка вручную: mx=0.18*600+0.02*1000=128, my=0.15*700+0.02*2000=145
    # x0=200-128=72, y0=900-145=755, x1=800+128=928, y1=1600+145=1745


def test_single_box_below_min_width_grows_symmetrically():
    """Слишком УЗКИЙ бокс (высота уже выше пола) — ширина добирается до 45% кадра
    СИММЕТРИЧНО (центр по x не должен сместиться), высота не трогается вовсе."""
    result = label_bbox([box(450, 900, 550, 1700)], [0.9], W, H)
    assert result is not None
    x0, y0, x1, y1 = result
    assert x1 - x0 == pytest.approx(0.45 * W)  # min_w
    assert (x0 + x1) / 2 == pytest.approx(500.0)  # центр не сместился — рост симметричный
    assert y1 - y0 == pytest.approx(1120.0)  # высота после одних полей — floor не сработал


def test_single_box_below_min_height_grows_downward_biased():
    """Слишком НИЗКИЙ бокс (ширина уже выше пола) — высота добирается до 32% кадра
    С ПЕРЕВЕСОМ ВНИЗ (0.3 добавки — вверх, 0.7 — вниз): шапка этикетки с
    винодельней уже найдена детектором вверху, а название/сахар — ниже неё."""
    result = label_bbox([box(250, 1000, 750, 1300)], [0.9], W, H)
    assert result is not None
    x0, y0, x1, y1 = result
    assert y1 - y0 == pytest.approx(0.32 * H)  # min_h — рост ровно до пола
    assert x1 - x0 == pytest.approx(720.0)  # ширина после одних полей — floor не сработал
    # до роста: y0=915, y1=1385 (только поля) -> add=640-470=170
    # рост вверх 0.3*170=51 (915->864), вниз 0.7*170=119 (1385->1504): вниз СТРОГО больше
    grown_up = 915.0 - y0
    grown_down = y1 - 1385.0
    assert grown_down > grown_up
    assert grown_up == pytest.approx(51.0)
    assert grown_down == pytest.approx(119.0)
    assert (x0, y0, x1, y1) == pytest.approx((140.0, 864.0, 860.0, 1504.0))


# --------------------------------------------------------------------------------------
# Кластеризация по вертикали — несколько боксов сливаются в один прямоугольник
# --------------------------------------------------------------------------------------


def test_two_vertically_close_boxes_merge_into_one_bbox():
    """Шапка винодельни (A) + название чуть ниже с разрывом (B), обе строки той же
    высоты — попадают в общий кластер (gap_y <= 6*med_h, есть горизонтальное
    перекрытие) — итоговый бокс охватывает ОБЕ строки, не только одну."""
    a = box(300, 1000, 700, 1060)  # высота 60
    b = box(320, 1150, 680, 1210)  # высота 60, разрыв от A: 1150-1060=90 <= 6*60=360
    result = label_bbox([a, b], [0.9, 0.9], W, H)
    assert result == pytest.approx((208.0, 842.4, 792.0, 1482.4))


def test_distant_box_does_not_merge_and_is_excluded_from_bbox():
    """Тот же старт (A), но вторая строка (D) слишком далеко по вертикали
    (gap_y > 6*med_h) — НЕ сливается: итоговый бокс построен ТОЛЬКО по A, D не
    расширяет его вниз."""
    a = box(300, 1000, 700, 1060)  # высота 60
    d = box(310, 1900, 690, 1960)  # высота 60, разрыв 1900-1060=840 > 6*60=360
    result = label_bbox([a, d], [0.9, 0.9], W, H)
    assert result is not None
    x0, y0, x1, y1 = result
    assert y1 < 1900.0  # не дотягивается до D вообще
    assert (x0, y0, x1, y1) == pytest.approx((208.0, 806.4, 792.0, 1446.4))


def test_horizontally_disjoint_box_does_not_merge_despite_vertical_proximity():
    """Бокс рядом по вертикали (gap_y мал), но БЕЗ горизонтального перекрытия
    (даже с запасом 0.1*w) — не сливается: пересечение по x должно быть строго
    положительным, не только близость по y."""
    a = box(300, 1000, 700, 1060)  # высота 60
    # far по x: x0=950 > bx1(700) + 0.1*w(100) = 800 -> overlap_x <= 0
    far_x = box(950, 1070, 1050, 1130)
    result = label_bbox([a, far_x], [0.9, 0.9], W, H)
    x0, y0, x1, y1 = result
    assert x1 < 950.0  # не расширился в сторону far_x


# --------------------------------------------------------------------------------------
# Отсечение по границам кадра
# --------------------------------------------------------------------------------------


def test_bbox_clamped_to_frame_bounds():
    """Бокс у верхнего края кадра — после полей и роста-вниз-с-перевесом уходит в
    отрицательные y0, обязан быть обрезан до 0 (не отдавать координаты вне кадра
    вызывающему коду, который будет резать по ним numpy-массив)."""
    result = label_bbox([box(450, 0, 550, 30)], [0.9], W, H)
    assert result is not None
    x0, y0, x1, y1 = result
    assert y0 == 0.0  # обрезано с отрицательного
    assert x0 >= 0.0 and y0 >= 0.0 and x1 <= W and y1 <= H
    assert (x0, y0, x1, y1) == pytest.approx((275.0, 0.0, 725.0, 439.2))


def test_scores_shorter_than_boxes_degrades_to_none_not_index_error():
    """`zip(boxes, scores)` молча обрезает по короткой стороне (та же дисциплина,
    что `cv.ocr_rapid.RapidOcrReader._extract_text()` для `txts`/`scores`) —
    несовпадение длин не должно поднимать исключение, максимум — меньше кандидатов."""
    result = label_bbox([box(300, 1000, 700, 1060)], [], W, H)
    assert result is None
